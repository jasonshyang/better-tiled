fn run(map: &Path, target: &Path, options: &Options) -> Result<Report, Error> {
    export(map, &mut bt_tmx::Loader::builder().build(), target, options)
}

fn replace() -> Options {
    Options {
        replace: true,
        ..Options::default()
    }
}

fn refused(result: Result<Report, Error>) -> Vec<Refusal> {
    match result {
        Err(Error::Refused(refusals)) => refusals,
        Err(e) => panic!("failed instead: {e}"),
        Ok(report) => panic!("exported instead: {:?}", report.files),
    }
}

fn states(report: &Report) -> Vec<(PathBuf, State)> {
    report
        .files
        .iter()
        .map(|f| (f.path.clone(), f.state))
        .collect()
}

fn uid_of(file: &Path) -> Option<String> {
    read::parse_header(&std::fs::read_to_string(file).unwrap())
        .unwrap()
        .uid()
}

/// Every file under `dir`, with its bytes and modification time.
fn listing(dir: &Path) -> Vec<(PathBuf, Vec<u8>, SystemTime)> {
    let mut out = Vec::new();
    let mut folders = vec![dir.to_path_buf()];
    while let Some(folder) = folders.pop() {
        for entry in std::fs::read_dir(&folder).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                folders.push(path);
            } else {
                out.push((
                    path.clone(),
                    std::fs::read(&path).unwrap(),
                    std::fs::metadata(&path).unwrap().modified().unwrap(),
                ));
            }
        }
    }
    out.sort();
    out
}

#[test]
fn generated_files_carry_a_header_with_the_hash_of_the_rest() {
    let dir = project("header");
    let target = dir.join("levels/features.tscn");
    run(&dir.join("maps/features.tmx"), &target, &Options::default()).unwrap();
    let tscn = std::fs::read_to_string(&target).unwrap();
    let lines: Vec<&str> = tscn.lines().take(4).collect();
    assert_eq!(
        lines[..2],
        [
            "; Generated by better-tiled from ../maps/features.tmx. Edit the map, or a scene that",
            "; inherits this one: changes made here are replaced by the next export."
        ]
    );
    let start = tscn.find("[gd_scene").unwrap();
    assert_eq!(
        lines[2],
        format!(
            "; better-tiled-export 1 fnv1a64={:016x}",
            fnv1a64(&tscn.as_bytes()[start..])
        )
    );
    let uid = uid_to_text(contract::derived_uid("res://levels/features.tscn", 0));
    assert_eq!(lines[3], format!("[gd_scene format=3 uid=\"{uid}\"]"));
    let resource = read::parse(&tscn).unwrap();
    assert_eq!(
        resource.root().unwrap().1.get("metadata/bt_source"),
        Some("\"../maps/features.tmx\""),
        "the root marker"
    );
    std::fs::remove_dir_all(&dir).ok();
}

