/// Scenes and TileSets Godot itself writes (ids of random letters) are a person's, with what they
/// hold; only Tiled's own numbering is Tiled's exporter.
#[test]
fn files_godot_wrote_are_told_from_tileds_exports_and_say_what_they_hold() {
    let dir = project("godot-made");
    let map = dir.join("maps/features.tmx");
    let target = dir.join("levels/features.tscn");
    std::fs::create_dir_all(dir.join("levels")).unwrap();
    let by_godot = "[gd_scene load_steps=4 format=3]\n\n[ext_resource type=\"Texture2D\" path=\"res://maps/tiles.png\" id=\"1_k3c2d\"]\n\n[sub_resource type=\"TileSetAtlasSource\" id=\"TileSetAtlasSource_btf3t\"]\ntexture = ExtResource(\"1_k3c2d\")\n\n[sub_resource type=\"TileSet\" id=\"TileSet_x7h2q\"]\nsources/0 = SubResource(\"TileSetAtlasSource_btf3t\")\n\n[node name=\"features\" type=\"Node2D\"]\n\n[node name=\"TileMap\" type=\"TileMap\" parent=\".\"]\ntile_set = SubResource(\"TileSet_x7h2q\")\nformat = 2\n\n[node name=\"Player\" type=\"Node2D\" parent=\".\"]\n";
    std::fs::write(&target, by_godot).unwrap();
    let refusal = refused(run(&map, &target, &Options::default())).remove(0);
    assert_eq!(refusal.found, Found::NoHeader);
    assert!(
        refusal.extras.contains(&"a Node2D 'Player'".to_owned()),
        "{:?}",
        refusal.extras
    );
    assert!(
        refusal.reason.contains("a person wrote it. It has ")
            && refusal.reason.contains("a Node2D 'Player'"),
        "{}",
        refusal.reason
    );
    // Tiled's: its TileSet_0; a script someone added is said.
    let tiled = by_godot.replace("TileSet_x7h2q", "TileSet_0").replace(
        "[node name=\"features\" type=\"Node2D\"]\n",
        "[node name=\"features\" type=\"Node2D\"]\nscript = ExtResource(\"9\")\n",
    );
    std::fs::write(&target, tiled).unwrap();
    let refusal = refused(run(&map, &target, &Options::default())).remove(0);
    assert_eq!(
        (refusal.found.clone(), refusal.extras.clone()),
        (
            Found::TiledExport,
            vec!["a script on 'features'".to_owned()]
        )
    );
    assert!(
        refusal
            .reason
            .ends_with("resPath objects stay instances. It has a script on 'features'."),
        "{}",
        refusal.reason
    );
    std::fs::remove_file(&target).unwrap();

    // A shared TileSet's place: Godot's numbering, then Tiled's.
    let room = dir.join("maps/room.tmx");
    std::fs::write(&room, ONE_TILE.replace(" <tileset firstgid", " <properties>\n  <property name=\"tilesetResPath\" value=\"res://tilesets/room.tres\"/>\n </properties>\n <tileset firstgid")).unwrap();
    let tres = dir.join("tilesets/room.tres");
    std::fs::create_dir_all(tres.parent().unwrap()).unwrap();
    let tileset = |id: &str| {
        format!(
            "[gd_resource type=\"TileSet\" load_steps=3 format=3]\n\n[ext_resource type=\"Texture2D\" path=\"res://maps/tiles.png\" id=\"1_k3c2d\"]\n\n[sub_resource type=\"TileSetAtlasSource\" id=\"{id}\"]\ntexture = ExtResource(\"1_k3c2d\")\n\n[resource]\nsources/0 = SubResource(\"{id}\")\n"
        )
    };
    std::fs::write(&tres, tileset("TileSetAtlasSource_btf3t")).unwrap();
    let scene = dir.join("levels/room.tscn");
    let refusal = refused(run(&room, &scene, &Options::default())).remove(0);
    assert_eq!(
        (refusal.path.clone(), refusal.found.clone()),
        (tres.clone(), Found::NoHeader)
    );
    std::fs::write(&tres, tileset("TileSetAtlasSource_0")).unwrap();
    assert_eq!(
        refused(run(&room, &scene, &Options::default()))[0].found,
        Found::TiledExport
    );
    std::fs::remove_dir_all(&dir).ok();
}

