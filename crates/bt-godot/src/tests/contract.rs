/// A scene Godot saved again away from where its map exports to (Godot's Duplicate keeps the
/// marker) is a copy: exporting every scene again leaves it alone.
#[test]
fn exporting_every_scene_again_leaves_copies_alone() {
    let dir = project("all-copies");
    let game = game(&dir);
    for name in ["a", "b"] {
        std::fs::write(dir.join(format!("maps/{name}.tmx")), ONE_TILE).unwrap();
        run(
            &dir.join(format!("maps/{name}.tmx")),
            &game.join(format!("levels/{name}.tscn")),
            &Options::default(),
        )
        .unwrap();
    }
    // As Godot's Duplicate writes it: no header, a uid of its own.
    let a = std::fs::read_to_string(game.join("levels/a.tscn")).unwrap();
    let uid = uid_of(&game.join("levels/a.tscn")).unwrap();
    let duplicate = a
        .lines()
        .filter(|l| !l.starts_with(';'))
        .collect::<Vec<_>>()
        .join("\n")
        .replace(&uid, "uid://bduplicate1")
        + "\n";
    let copy = game.join("levels/a_copy.tscn");
    std::fs::write(&copy, &duplicate).unwrap();
    for options in [Options::default(), replace()] {
        let all = export_all(
            &game,
            &mut |_| Ok(bt_tmx::Loader::builder().build()),
            &options,
        )
        .unwrap();
        let outcomes: Vec<(PathBuf, bool)> = all
            .scenes
            .iter()
            .map(|e| (e.scene.clone(), e.outcome.is_ok()))
            .collect();
        assert_eq!(
            outcomes,
            [
                (game.join("levels/a.tscn"), true),
                (game.join("levels/b.tscn"), true)
            ]
        );
        assert!(all.written);
        assert_eq!(
            all.copies,
            [crate::SceneCopy {
                scene: copy.clone(),
                map: dir.join("maps/a.tmx")
            }]
        );
        assert_eq!(
            std::fs::read_to_string(&copy).unwrap(),
            duplicate,
            "never touched"
        );
        assert!(!game.join("levels/a_copy.tscn.bak").exists());
    }
    // Saved again by Godot where the map exports to, it is the export, refused as such.
    std::fs::remove_file(&copy).unwrap();
    std::fs::write(dir.join("maps/a.tmx"), ONE_TILE.replace(" <tileset", " <editorsettings>\n  <export target=\"../game/levels/a.tscn\" format=\"tscn\"/>\n </editorsettings>\n <tileset")).unwrap();
    std::fs::write(
        game.join("levels/a.tscn"),
        a.lines().skip(3).collect::<Vec<_>>().join("\n") + "\n",
    )
    .unwrap();
    let scenes = generated_scenes(&game);
    assert_eq!((scenes.generated.len(), scenes.copies.len()), (2, 0));
    let all = export_all(
        &game,
        &mut |_| Ok(bt_tmx::Loader::builder().build()),
        &Options::default(),
    )
    .unwrap();
    assert!(
        !all.written
            && matches!(&all.scenes[0].outcome, Err(Error::Refused(r)) if r[0].found == Found::ResavedByGodot)
    );
    std::fs::remove_dir_all(&dir).ok();
}
