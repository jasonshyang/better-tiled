#[test]
fn every_state_of_a_generated_file() {
    let dir = project("states");
    let map = dir.join("maps/features.tmx");
    let target = dir.join("levels/features.tscn");
    let found = |result| {
        refused(result)
            .into_iter()
            .map(|r| (r.path, r.found))
            .collect::<Vec<_>>()
    };

    // Nothing there: written.
    let report = run(&map, &target, &Options::default()).unwrap();
    assert_eq!(states(&report), [(target.clone(), State::Written)]);
    let uid = uid_of(&target).unwrap();
    // The same bytes: left alone.
    let report = run(&map, &target, &Options::default()).unwrap();
    assert!(
        report.up_to_date() && states(&report) == [(target.clone(), State::Unchanged)],
        "{:?}",
        report.files
    );
    // Its own, the map changed: replaced, keeping the uid.
    std::fs::write(&map, FEATURES.replace("a test room", "a bigger room")).unwrap();
    let report = run(&map, &target, &Options::default()).unwrap();
    assert_eq!(states(&report), [(target.clone(), State::Written)]);
    assert!(
        std::fs::read_to_string(&target)
            .unwrap()
            .contains("a bigger room")
    );
    assert_eq!(uid_of(&target).unwrap(), uid);
    let ours = std::fs::read_to_string(&target).unwrap();

    // Another map's export.
    let other = refused(run(
        &dir.join("maps/level.tmx"),
        &target,
        &Options::default(),
    ));
    assert_eq!(
        other[0].found,
        Found::OtherMap("../maps/features.tmx".to_owned())
    );
    assert!(
        other[0]
            .reason
            .contains("the export of ../maps/features.tmx, not of ../maps/level.tmx"),
        "{}",
        other[0].reason
    );

    // Edited by hand: refused, saying what it has that the export lacks.
    let cells = "[node name=\"cells\" type=\"TileMapLayer\" parent=\".\"]\n";
    std::fs::write(
        &target,
        ours.replace("texture_filter = 1", "texture_filter = 2")
            .replace(cells, &format!("{cells}z_index = 3\n")),
    )
    .unwrap();
    let edited = refused(run(&map, &target, &Options::default()));
    assert_eq!(
        (edited[0].path.clone(), edited[0].found.clone()),
        (target.clone(), Found::Edited)
    );
    assert_eq!(edited[0].extras, ["z_index on 'cells'"]);
    assert!(
        edited[0].reason.contains(
            "It has z_index on 'cells'. Keep Godot work in a scene that inherits features.tscn."
        ),
        "{}",
        edited[0].reason
    );

    // Saved again by Godot: no header, the marker kept, and what was added in Godot listed.
    let body = &ours[ours.find("[gd_scene").unwrap()..];
    let resaved = body.replace("[node name=\"features\" type=\"Node2D\"]\n", "[node name=\"features\" type=\"Node2D\" unique_id=1234]\nscript = ExtResource(\"9_ab12c\")\n")
        + "\n[node name=\"Camera\" type=\"Camera2D\" parent=\".\" unique_id=99]\n\n[connection signal=\"ready\" from=\".\" to=\".\" method=\"_on_ready\"]\n";
    std::fs::write(&target, &resaved).unwrap();
    let godot = refused(run(&map, &target, &Options::default()));
    assert_eq!(godot[0].found, Found::ResavedByGodot);
    assert_eq!(
        godot[0].extras,
        [
            "a script on 'features'",
            "a Camera2D 'Camera'",
            "a signal connection",
            "a unique_id the export didn't write"
        ]
    );
    assert!(
        godot[0]
            .reason
            .starts_with("Godot saved it again after better-tiled exported it"),
        "{}",
        godot[0].reason
    );
    assert!(godot[0].reason.contains("It has a script on 'features', a Camera2D 'Camera', a signal connection and a unique_id the export didn't write."), "{}", godot[0].reason);

    // Tiled's exporter: one TileMap with format = 2.
    let tiled = "[gd_scene load_steps=3 format=3]\n\n[ext_resource type=\"Texture2D\" path=\"res://maps/tiles.png\" id=\"1\"]\n\n[sub_resource type=\"TileSet\" id=\"TileSet_0\"]\n\n[node name=\"features\" type=\"Node2D\"]\n\n[node name=\"TileMap\" type=\"TileMap\" parent=\".\"]\ntile_set = SubResource(\"TileSet_0\")\nformat = 2\n";
    std::fs::write(&target, tiled).unwrap();
    assert_eq!(
        found(run(&map, &target, &Options::default())),
        [(target.clone(), Found::TiledExport)]
    );
    let reason = refused(run(&map, &target, &Options::default()))
        .remove(0)
        .reason;
    assert!(
        reason.contains("one TileMapLayer per layer") && reason.contains("$TileMap"),
        "{reason}"
    );

    // No header: an earlier better-tiled (today's exports), a person, or not a scene at all.
    std::fs::write(
        &target,
        "[gd_scene format=3]\n\n[node name=\"features\" type=\"Node2D\"]\ntexture_filter = 1\n",
    )
    .unwrap();
    assert_eq!(
        found(run(&map, &target, &Options::default())),
        [(target.clone(), Found::NoHeader)]
    );
    std::fs::write(&target, "edited by hand").unwrap();
    assert_eq!(
        found(run(&map, &target, &Options::default())),
        [(target.clone(), Found::NoHeader)]
    );

    // A header whose hash is wrong, from a version of the header this one doesn't know: edited.
    let newer = ours.replace("better-tiled-export 1 ", "better-tiled-export 2 ");
    std::fs::write(&target, newer).unwrap();
    assert_eq!(
        found(run(&map, &target, &Options::default())),
        [(target.clone(), Found::Edited)]
    );

    // Replace writes over each, and then the file is the export's own again.
    let report = run(&map, &target, &replace()).unwrap();
    assert!(states(&report).contains(&(target.clone(), State::Written)));
    assert_eq!(uid_of(&target).unwrap(), uid);
    assert!(
        run(&map, &target, &Options::default())
            .unwrap()
            .up_to_date()
    );
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn replace_keeps_each_old_file_beside_it_without_its_uid() {
    let dir = project("backups");
    let map = dir.join("maps/features.tmx");
    let target = dir.join("levels/features.tscn");
    run(&map, &target, &Options::default()).unwrap();
    let uid = uid_of(&target).unwrap();
    let edited = std::fs::read_to_string(&target).unwrap()
        + "\n[node name=\"Player\" type=\"Node2D\" parent=\".\"]\n";
    std::fs::write(&target, &edited).unwrap();
    let refusal = refused(run(&map, &target, &Options::default())).remove(0);
    assert_eq!(refusal.extras, ["a Node2D 'Player'"]);
    assert!(
        refusal.way_out().contains("--replace"),
        "{}",
        refusal.way_out()
    );

    let report = run(&map, &target, &replace()).unwrap();
    let backup = dir.join("levels/features.tscn.bak");
    assert_eq!(
        states(&report),
        [
            (backup.clone(), State::BackedUp),
            (target.clone(), State::Written)
        ]
    );
    assert_eq!(
        std::fs::read_to_string(&backup).unwrap(),
        edited.replace(&format!(" uid=\"{uid}\""), ""),
        "the old file, but for its uid"
    );
    assert_eq!(uid_of(&backup), None);
    assert_eq!(uid_of(&target).unwrap(), uid, "the new file keeps the uid");

    // The next backup never overwrites the first.
    let edited_again = std::fs::read_to_string(&target)
        .unwrap()
        .replace("texture_filter = 1", "texture_filter = 0");
    std::fs::write(&target, &edited_again).unwrap();
    run(&map, &target, &replace()).unwrap();
    assert_eq!(
        std::fs::read_to_string(dir.join("levels/features.tscn.2.bak")).unwrap(),
        edited_again.replace(&format!(" uid=\"{uid}\""), "")
    );
    assert_eq!(
        std::fs::read_to_string(&backup).unwrap(),
        edited.replace(&format!(" uid=\"{uid}\""), "")
    );
    assert!(
        run(&map, &target, &Options::default())
            .unwrap()
            .up_to_date()
    );
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn a_refused_export_writes_nothing_not_even_image_copies() {
    let dir = project("nothing");
    let game = game(&dir);
    let target = game.join("levels/level.tscn");
    std::fs::create_dir_all(target.parent().unwrap()).unwrap();
    std::fs::write(
        &target,
        "[gd_scene format=3]\n\n[node name=\"level\" type=\"Node2D\"]\n",
    )
    .unwrap();
    let before = listing(&dir);
    let refusals = refused(run(
        &dir.join("maps/level.tmx"),
        &target,
        &Options::default(),
    ));
    assert_eq!(
        refusals.iter().map(|r| r.found.clone()).collect::<Vec<_>>(),
        [Found::NoHeader]
    );
    assert_eq!(
        listing(&dir),
        before,
        "no copy, no list of copies, no folder"
    );
    assert!(!game.join("levels/images").exists());

    // --check, even with --replace, only says what would happen.
    let check = Options {
        check: true,
        replace: true,
        ..Options::default()
    };
    let report = run(&dir.join("maps/level.tmx"), &target, &check).unwrap();
    assert!(report.checked && !report.up_to_date());
    let copy = game.join("levels/images/tiles.png");
    let manifest = game.join("levels/images/.sources.json");
    let backup = game.join("levels/level.tscn.bak");
    assert_eq!(
        states(&report),
        [
            (copy, State::Copied),
            (backup, State::BackedUp),
            (target.clone(), State::Written),
            (manifest, State::Written)
        ]
    );
    assert_eq!(listing(&dir), before);
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn an_identical_export_touches_nothing() {
    let dir = project("identical");
    let game = game(&dir);
    let target = game.join("levels/level.tscn");
    let report = run(&dir.join("maps/level.tmx"), &target, &Options::default()).unwrap();
    assert_eq!(report.copied(), 1);
    // Old times, so a rewrite would show however fast it is.
    let old = SystemTime::UNIX_EPOCH + Duration::from_secs(1_000_000_000);
    for (path, _, _) in listing(&game) {
        std::fs::File::options()
            .write(true)
            .open(&path)
            .unwrap()
            .set_modified(old)
            .unwrap();
    }
    let before = listing(&game);
    let report = run(&dir.join("maps/level.tmx"), &target, &Options::default()).unwrap();
    assert!(report.up_to_date(), "{:?}", report.files);
    assert_eq!(listing(&game), before);
    assert!(before.iter().all(|(_, _, time)| *time == old));
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn derived_uids_come_from_the_res_path() {
    let id = contract::derived_uid("res://levels/desert.tscn", 0);
    assert_eq!(id, fnv1a64(b"res://levels/desert.tscn") & (u64::MAX >> 1));
    assert_eq!(
        contract::derived_uid("res://levels/desert.tscn", 0),
        id,
        "the same every time"
    );
    assert_eq!(read::text_to_uid(&uid_to_text(id)), Some(id));
    assert_ne!(
        contract::derived_uid("res://levels/desert.tscn", 1),
        id,
        "salted"
    );
    assert_eq!(
        uid_to_text(123456789),
        "uid://cyncsb",
        "Godot's text for it"
    );

    // Deleting the scene and exporting again gives the same uid.
    let dir = project("uids");
    let target = dir.join("levels/features.tscn");
    run(&dir.join("maps/features.tmx"), &target, &Options::default()).unwrap();
    let uid = uid_of(&target).unwrap();
    assert_eq!(
        uid,
        uid_to_text(contract::derived_uid("res://levels/features.tscn", 0))
    );
    std::fs::remove_file(&target).unwrap();
    run(&dir.join("maps/features.tmx"), &target, &Options::default()).unwrap();
    assert_eq!(uid_of(&target).unwrap(), uid);
    std::fs::remove_dir_all(&dir).ok();
}

#[test]
fn a_uid_another_file_has_is_refused_as_moved_or_in_use() {
    let dir = project("taken");
    let map = dir.join("maps/features.tmx");
    let target = dir.join("levels/place.tscn");
    run(&map, &target, &Options::default()).unwrap();

    // The scene moved in Godot: it still carries the uid derived from its old place.
    let moved = dir.join("levels/w1/place.tscn");
    std::fs::create_dir_all(moved.parent().unwrap()).unwrap();
    std::fs::rename(&target, &moved).unwrap();
    let refusal = refused(run(&map, &target, &Options::default())).remove(0);
    assert_eq!(refusal.found, Found::Moved(moved.clone()));
    assert!(
        refusal
            .reason
            .contains("moved in Godot to res://levels/w1/place.tscn"),
        "{}",
        refusal.reason
    );
    assert!(
        refusal.way_out().contains("levels/w1/place.tscn")
            && refusal.way_out().contains("--new-uid"),
        "{}",
        refusal.way_out()
    );
    assert_eq!(
        status(&map, &mut bt_tmx::Loader::builder().build(), &target)
            .unwrap()
            .summary(),
        Summary::Moved(moved.clone())
    );
    assert_eq!(
        refused(run(&map, &target, &replace()))[0].found,
        Found::Moved(moved.clone()),
        "Replace doesn't give a uid of its own"
    );
    // --new-uid starts a new scene, with a uid nothing else has.
    run(
        &map,
        &target,
        &Options {
            new_uid: true,
            ..Options::default()
        },
    )
    .unwrap();
    let (new, old) = (uid_of(&target).unwrap(), uid_of(&moved).unwrap());
    assert_ne!(new, old);
    assert_eq!(
        new,
        uid_to_text(contract::derived_uid("res://levels/place.tscn", 1))
    );
    assert!(
        run(&map, &target, &Options::default())
            .unwrap()
            .up_to_date(),
        "the new uid is kept"
    );

    // Another file with the uid a new scene would get.
    let uid = |res: &str| uid_to_text(contract::derived_uid(res, 0));
    std::fs::create_dir_all(dir.join("other")).unwrap();
    std::fs::write(
        dir.join("other/x.tscn"),
        format!(
            "[gd_scene format=3 uid=\"{}\"]\n\n[node name=\"x\" type=\"Node2D\"]\n",
            uid("res://levels/new.tscn")
        ),
    )
    .unwrap();
    let refusal = refused(run(&map, &dir.join("levels/new.tscn"), &Options::default())).remove(0);
    assert_eq!(refusal.found, Found::UidInUse(dir.join("other/x.tscn")));
    assert!(
        refusal
            .reason
            .starts_with("res://other/x.tscn already has the uid"),
        "{}",
        refusal.reason
    );
    assert!(!dir.join("levels/new.tscn").exists());
    // A script's .uid file and an image's .import file carry uids too.
    std::fs::create_dir_all(dir.join("scripts")).unwrap();
    std::fs::write(
        dir.join("scripts/a.gd.uid"),
        uid("res://levels/third.tscn") + "\n",
    )
    .unwrap();
    assert_eq!(
        refused(run(
            &map,
            &dir.join("levels/third.tscn"),
            &Options::default()
        ))[0]
            .found,
        Found::UidInUse(dir.join("scripts/a.gd"))
    );
    std::fs::write(
        dir.join("maps/tiles.png.import"),
        format!(
            "[remap]\n\nimporter=\"texture\"\nuid=\"{}\"\n",
            uid("res://levels/fourth.tscn")
        ),
    )
    .unwrap();
    assert_eq!(
        refused(run(
            &map,
            &dir.join("levels/fourth.tscn"),
            &Options::default()
        ))[0]
            .found,
        Found::UidInUse(dir.join("maps/tiles.png"))
    );
    std::fs::remove_dir_all(&dir).ok();
}

/// A read-only scene fails the export (exit 1), whatever it holds: it is never made writable,
/// replaced or refused as changed.
#[cfg(unix)]
#[test]
fn a_read_only_scene_fails_the_export_even_when_it_is_the_exports_own() {
    use std::os::unix::fs::PermissionsExt;
    let dir = project("read-only");
    let map = dir.join("maps/features.tmx");
    let target = dir.join("levels/features.tscn");
    run(&map, &target, &Options::default()).unwrap();
    std::fs::set_permissions(&target, std::fs::Permissions::from_mode(0o444)).unwrap();
    assert!(
        run(&map, &target, &Options::default())
            .unwrap()
            .up_to_date(),
        "nothing to write is fine"
    );
    std::fs::write(&map, FEATURES.replace("a test room", "a bigger room")).unwrap();
    let before = std::fs::read(&target).unwrap();
    for options in [Options::default(), replace()] {
        match run(&map, &target, &options) {
            Err(Error::Failed(e)) => {
                assert!(e.contains("features.tscn: the file is read-only"), "{e}")
            }
            other => panic!("{:?}", other.map(|r| r.files)),
        }
    }
    assert_eq!(std::fs::read(&target).unwrap(), before);
    std::fs::set_permissions(&target, std::fs::Permissions::from_mode(0o644)).unwrap();
    std::fs::remove_dir_all(&dir).ok();
}

